import CryptoKit
import Foundation

/// Снимок файла хранилища: то немногое, чего хватает, чтобы понять,
/// трогали ли его с прошлой сверки.
///
/// Содержимого здесь нет намеренно. Хранилище бывает на тысячи заметок,
/// и читать их все каждые пятнадцать минут ради отпечатка — впустую гонять
/// диск. Дата правки и размер отвечают на вопрос «менялось ли» даром, прямо
/// обходом дерева; отпечаток считается уже потом и только у тех файлов,
/// у кого эти два числа разошлись с записанными.
struct VaultFile: Equatable {
    /// Путь от корня хранилища: `Проекты/Роадмап.md`. Без ведущей косой.
    let path: String

    /// Дата правки файла на диске.
    let modified: Date

    /// Размер в байтах.
    let size: Int

    /// Имя заметки — имя файла без расширения.
    ///
    /// В Obsidian это и есть заголовок: `# Заголовок` внутри файла —
    /// уже часть текста, и ссылаются заметки друг на друга не на него.
    /// Ссылка `[[Роадмап]]` указывает именно на имя файла.
    var title: String {
        (path as NSString).lastPathComponent.replacingOccurrences(
            of: ".md",
            with: "",
            options: [.caseInsensitive, .anchored, .backwards]
        )
    }

    /// Отпечаток содержимого.
    ///
    /// Он нужен не только для «изменилось ли». По нему узнаётся **своя же
    /// запись**: приложение кладёт файл, слежение за папкой тут же сообщает
    /// об изменении, и без отпечатка сверка приняла бы собственную запись
    /// за чужую правку — и так по кругу.
    static func hash(of text: String) -> String {
        var hasher = SHA256()
        hasher.update(data: Data(text.utf8))
        return hasher.finalize().map { String(format: "%02x", $0) }.joined()
    }
}

import Foundation

extension Timer {
    /// Разрешить системе сдвигать срабатывание на десятую долю шага.
    ///
    /// Без допуска каждый таймер будит процессор в свою точную миллисекунду,
    /// и два десятка опросов приложения — погода, календарь, буфер, встречи —
    /// просыпаются порознь. С допуском система собирает соседние пробуждения
    /// в одно (`ENERGY.md`, О6).
    ///
    /// Только для фоновых опросов, где десятая доля шага ничего не меняет.
    /// Опросу мыши, голосу и анимациям допуск не ставится: там опоздание
    /// видно рукой и глазом.
    func allowCoalescing() {
        tolerance = timeInterval / 10
    }
}

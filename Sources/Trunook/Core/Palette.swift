import SwiftUI

/// Цвета приложения, названные по смыслу, а не по оттенку.
///
/// Раньше палитра была у окна знакомства, а панели выреза и настройки брали
/// системные `.cyan`, `.mint`, `.orange` по месту. Один и тот же смысл —
/// «полка оранжевая» — был записан в трёх файлах, и экраны выглядели
/// собранными из разных приложений.
///
/// Имена по смыслу, а не по цвету, потому что смысл переживает перекраску:
/// сменить оттенок полки — это правка одной строки здесь, а не поиск слова
/// «orange» по всему коду.
enum Palette {
    // MARK: Оттенки
    //
    // Взяты из окна знакомства: они подбирались под тёмный фон и на нём
    // не выцветают, в отличие от системных, рассчитанных на оба режима.

    static let cyan = Color(red: 0.36, green: 0.86, blue: 1.0)
    static let violet = Color(red: 0.62, green: 0.44, blue: 1.0)
    static let mint = Color(red: 0.42, green: 0.95, blue: 0.75)
    static let amber = Color(red: 1.0, green: 0.72, blue: 0.35)
    static let rose = Color(red: 1.0, green: 0.45, blue: 0.5)

    // Ещё два — заведены не для красоты, а по счёту.
    //
    // Пяти оттенков не хватало на пятнадцать разделов настроек, и раздача
    // сошлась так, что **пять разделов из пятнадцати** оказались одного
    // фиолетового: ИИ, Голос, Заметки, Телесуфлер и Инфо. Плитка со значком
    // в полосе разделов заведена ровно затем, чтобы раздел узнавался боковым
    // зрением быстрее, чем по названию, — а пять одинаковых плиток подряд
    // боковым зрением не различаются никак.
    //
    // Синий отодвинут от бирюзового настолько, чтобы их не путать в плитке
    // в двадцать точек: у бирюзового зелёная составляющая почти в потолке,
    // у синего — вдвое ниже. Зелёный так же отодвинут от мятного: мятный
    // светлый и холодный, этот темнее и теплее.
    static let blue = Color(red: 0.36, green: 0.55, blue: 1.0)
    static let green = Color(red: 0.40, green: 0.82, blue: 0.45)

    // MARK: Смыслы

    /// Быстрые команды и всё, что запускается по клавише.
    static let commands = mint
    /// Буфер обмена.
    static let clipboard = cyan
    /// Полка для файлов.
    static let shelf = amber
    /// Знакомство и ответ модели — всё, что «показывает и объясняет».
    static let welcome = violet
    static let assistant = violet
    /// Нагрузка на систему.
    static let monitor = cyan
    /// Таймер и секундомер.
    static let timer = rose
    /// Голос: как **спрашивают**, а не кто отвечает.
    ///
    /// Отвечает всё равно модель, и свечение острова во время ответа
    /// остаётся её фиолетовым — это про ответ. А раздел настроек, шапка
    /// и значок голоса — про способ задать вопрос, и у него свой цвет.
    /// Держать их одним значило снова красить пять разделов одинаково.
    static let voice = blue

    /// Заметки — то, что человек написал сам.
    ///
    /// Были фиолетовыми, как всё «объясняющее», и это было натяжкой: модель
    /// к заметке не причастна вовсе, её пишут руками.
    static let notes = green

    /// Телесуфлер — своё содержимое, набранное заранее и читаемое вслух.
    ///
    /// Был фиолетовым, как «показывает и объясняет». Стал янтарным, рядом
    /// с полкой: обе про **своё принесённое**, а не про ответ модели.
    static let teleprompter = amber
    /// Бодрость: экран, которому не дают гаснуть. Тёплый — как кофе,
    /// и заметный на чёрном, потому что подложка под чашкой это единственное,
    /// чем состояние и показано.
    static let caffeine = amber
    /// Погода и календарь.
    static let weather = cyan
    static let calendar = rose
    /// Подложка обычного окна — знакомства и настроек.
    ///
    /// Почти чёрная с холодным отливом: окна показывают вырез, а он чёрный.
    /// Ровный системный серый читался бы как чужое приложение, открытое рядом.
    /// Жила в `WelcomePalette`, пока принадлежала одному окну.
    static let windowBase = Color(red: 0.035, green: 0.043, blue: 0.075)

    /// Панель целиком и прочее без собственного цвета.
    static let panel = Color.white
    static let neutral = Color.white.opacity(0.55)

    // MARK: Состояния

    static let positive = mint
    static let warning = amber
    static let negative = rose
}

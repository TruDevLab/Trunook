/// Куда переедет подсветка при шаге стрелкой.
///
/// Одно правило на все списки, по которым ходят клавишами: команды в панели
/// разговора и строки истории буфера. Правило было выписано дважды и разошлось
/// бы при первой правке — а оно не самоочевидное и держится на двух решениях.
///
/// **Первое нажатие ставит подсветку на край**: сверху при ↓, снизу при ↑.
/// Не на первую строку в обоих случаях: ↑ означает «снизу вверх», и прыжок
/// им на самый верх читается как промах.
///
/// **По кругу подсветка не ходит.** Дойдя до края, она там и стоит. Замкнутое
/// кольцо в списке из трёх строк означало бы, что зажатая стрелка бесконечно
/// бегает по кругу и понять, где ты, нельзя.
enum HighlightMove {
    static func next<ID: Equatable>(from current: ID?, in ids: [ID], offset: Int) -> ID? {
        guard !ids.isEmpty else { return nil }
        guard let current, let index = ids.firstIndex(of: current) else {
            return offset > 0 ? ids.first : ids.last
        }
        return ids[min(max(0, index + offset), ids.count - 1)]
    }
}

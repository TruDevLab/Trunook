import SwiftUI
import AppKit

/// Поверхность: стекло там, где оно есть, заливка там, где его нет.
///
/// Единственное место, где приложение решает, чем рисовать подложку. До этого
/// подложки рисовались по месту одной и той же строкой
/// `RoundedRectangle(...).fill(.white.opacity(0.08))` — плитка, строка списка,
/// карточка встречи и круглая кнопка отличались только скруглением. Глубина
/// была выражена ровно одним средством, и уровни вложенности сливались:
/// три карточки нагрузки на чёрном читались одним прямоугольником с полосками.
///
/// ## Четыре условия, а не одно
///
/// Стекло рисуется, только если сошлось всё:
///
/// 1. **Система умеет.** `glassEffect` — с macOS 26. Ниже остаётся прежняя
///    заливка, и это не заглушка: она посчитана и выверена по контрасту,
///    см. лестницу прозрачностей в `NotchStyle`.
/// 2. **Человек не отказался.** `Settings.notchLook` в крайней правой
///    точке возвращает вырезу сплошную черноту; прочие положения меняют
///    стекло и затемнения, не отменяя его.
/// 3. **Система не просила уплотнить.** «Уменьшить прозрачность» — настройка
///    ровно про это, и половинчато её выполнять нельзя: кому полупрозрачные
///    слои читать трудно, тому трудно и полупрозрачное стекло.
///
///    Уйти на плоскую ветку целиком, а не уплотнять стекло: плоская ветка
///    выверена по контрасту на чёрном и проверена, а уплотнённое стекло —
///    это то же стекло, только гуще, и порог оно проходит не по расчёту,
///    а на глазок. Заодно снимается двойное уплотнение: `NotchStyle.dense()`
///    поднимал бы плотность заливок поверх того, что система уже сделала
///    со стеклом сама.
/// 4. **Не идёт съёмка.** См. ниже.
///
/// ## Почему снимок обязан уметь без стекла
///
/// `WindowSnapshot` рисует слой окна через `layer.render(in:)`, а стекло —
/// эффект уровня компоновщика: в слое его нет. Проверено пробой: соседние
/// блоки, снятые разом, дали подложку у того, что без стекла, и одни голые
/// буквы у того, что со стеклом.
///
/// То есть с приходом стекла отладочные снимки перестают показывать вёрстку —
/// а это единственный способ проверить её из сессии, без глаз человека.
/// Флаг возвращает снимкам смысл:
///
/// ```
/// defaults write com.trunook.Trunook debugFlatSurfaces -bool YES
/// ```
///
/// Проверяется он не на отдельных экранах, а на тех же самых: снимок должен
/// показывать ту вёрстку, которая работает, а не похожую на неё.
enum Surface {

    // MARK: - Насколько плотно

    /// Вид выреза — один ползунок на пять положений: слева прозрачное
    /// стекло с линзой, посередине матовое, справа сплошной чёрный.
    ///
    /// Прежде ползунков было два — «затемнение» и «прозрачность», — потом
    /// один плавный; пользователь попросил пять положений, каждое проверено
    /// снимком на читаемость.
    enum LookScale {
        /// Прозрачное стекло с линзой.
        static let glass = 0
        /// Стекло с линзой и дымкой под ним — по умолчанию.
        static let hazy = 25
        /// Матовое стекло — прежний вид.
        static let matte = 50
        /// Матовое темнее.
        static let dark = 75
        /// Стекла нет, вырез сплошь чёрный.
        static let opaque = 100

        static let steps = [glass, hazy, matte, dark, opaque]

        /// Что стоит, пока человек не выбрал сам.
        static let standard = hazy

        /// Ближайшее из пяти положений.
        static func snap(_ level: Int) -> Int {
            steps.min { abs($0 - level) < abs($1 - level) } ?? matte
        }

        /// Слово рядом с ползунком: доля сама по себе ничего не значит.
        static func title(for level: Int) -> String {
            switch snap(level) {
            case glass: return t("Стекло")
            case hazy: return t("Полупрозрачное")
            case matte: return t("Матовое")
            case dark: return t("Темнее")
            default: return t("Чёрный")
            }
        }
    }

    /// Во сколько раз плотнее обычного затемнять под стеклом.
    ///
    /// Одно число на все затемнения сразу — панели, плитки, строки, кнопки,
    /// плашку подписи, заливку главного действия. Порознь их пришлось бы
    /// подбирать пятью наборами, и они разъехались бы при первой же правке
    /// одного из них.
    static var scrimScale: Double { GlassLook.current.scrimScale }

    /// Затемнение, приведённое к выбранной плотности.
    ///
    /// Потолок нужен: справа от середины плашка подписи с её 0.58 ушла бы
    /// за единицу. SwiftUI такое значение примет молча, и потолок пришлось
    /// бы искать глазами.
    static func scrim(_ value: Double) -> Double {
        min(0.98, value * scrimScale)
    }

    /// Доля матового стекла у панели: 1 — матовое, 0 — линза.
    static var frost: Double { GlassLook.current.frost }

    /// Вид стекла в вырезе — одним значением на всё дерево выреза.
    ///
    /// Через `Environment`, а не чтением настроек по месту: модификатор
    /// поверхности SwiftUI пересчитывает, только когда меняются его входы,
    /// и плитка, чьи входы от ползунка не зависят, так и оставалась
    /// прежней. Среду же получают все, кто её читает.
    ///
    /// Плитки и кнопки — всегда матовое стекло с затемнением. На прозрачном
    /// фоне это и отделяет их от резких обоев. На матовом пробовали
    /// прозрачные плитки с кромкой — пользователь попросил вернуть матовое
    /// и «Темнее» ровно к прежнему виду.
    struct GlassLook: Equatable {
        /// Доля матового стекла у панели: 1 — матовое, 0 — линза.
        var frost: Double
        /// Множитель затемнений.
        var scrimScale: Double
        /// Затемнение под всей панелью, в долях обычного.
        var panelScrimFactor: Double
        /// Затемнение под матовой плиткой, в долях обычного.
        var surfaceScrimFactor: Double = 1

        /// Пять положений ползунка.
        static func step(_ level: Int) -> GlassLook {
            switch LookScale.snap(level) {
            case LookScale.glass:
                // Панель без черноты вовсе; плитки матовые и темнее
                // обычного: в светлой теме за ними светлые окна, и при
                // обычном затемнении серые подписи на них терялись
                // (снято снимком).
                return GlassLook(frost: 0, scrimScale: 1, panelScrimFactor: 0, surfaceScrimFactor: 1.3)
            case LookScale.hazy:
                // Линза с дымкой: обои видны, но притушены.
                return GlassLook(frost: 0, scrimScale: 1, panelScrimFactor: 1.6, surfaceScrimFactor: 1.2)
            case LookScale.matte:
                // Ровно прежнее «как обычно»: затемнения, подобранные живьём.
                return GlassLook(frost: 1, scrimScale: 1, panelScrimFactor: 1)
            default:
                // Темнее — темнеет панель, а плитки и кнопки остаются почти
                // как на матовом: с общим множителем они уходили в черноту
                // (0.42 × 1.75 у плитки) и сливались с панелью — поймал
                // пользователь. У чёрного стекла нет, и значения нужны только
                // плашке подписи.
                return GlassLook(frost: 1, scrimScale: 1.75, panelScrimFactor: 1, surfaceScrimFactor: 0.6)
            }
        }

        static var current: GlassLook { step(Settings.shared.notchLook) }

        /// Вне выреза — прежнее матовое: ползунок только про вырез.
        static var outsideNotch: GlassLook {
            GlassLook(frost: 1, scrimScale: 1, panelScrimFactor: 1)
        }

        /// Затемнение под плиткой.
        func surfaceScrim(_ base: Double) -> Double {
            min(0.98, base * scrimScale * surfaceScrimFactor)
        }

        /// Насколько плотно лежит цвет под стеклом у главного действия.
        ///
        /// Не в полную силу: сплошная заливка не пускает стекло сквозь себя,
        /// и кнопка выходит наклейкой на стеклянной плашке. Вполсилы цвет
        /// остаётся собой — по нему подобрана подпись, — но преломление
        /// и то, что за плашкой, сквозь него читаются.
        ///
        /// На плоской ветке не применяется: без стекла просвечивать нечему,
        /// и ослабленный цвет там был бы просто бледным.
        var accentFill: Double { min(0.98, 0.5 * scrimScale) }

        /// Затемнение под всей панелью.
        func panelScrim(_ base: Double) -> Double {
            min(0.98, base * scrimScale * panelScrimFactor)
        }
    }

    // MARK: - Когда стекло

    /// Умеет ли система. Внутри вида это условие всё равно придётся написать
    /// ещё раз — `#available` не выражается значением, — но решение о том,
    /// рисовать ли стекло **вообще**, должно читаться в одном месте.
    static var isSupported: Bool {
        if #available(macOS 26.0, *) { return true }
        return false
    }

    /// Плоская съёмка: подложки рисуются заливкой, чтобы попасть в снимок.
    ///
    /// Читается живьём, а не при запуске: флаг отладочный, и перезапуск между
    /// «включил» и «снял» — лишний шаг там, где их и так хватает.
    static var isFlatForSnapshot: Bool {
        UserDefaults.standard.bool(forKey: "debugFlatSurfaces")
    }

    /// Стекло в вырезе.
    ///
    /// Настройка человека спрашивается только здесь: `opaqueNotch` — про
    /// вырез, а не про приложение. Окно настроек и окно знакомства стоят
    /// на своём фоне, и чернота выреза к ним отношения не имеет.
    static var inNotch: Bool {
        isSupported && !isFlatForSnapshot
            && Settings.shared.notchLook < LookScale.opaque
            && !MotionPreference.shared.reduceTransparency
    }

    /// Считается ли вырез прозрачным — то есть растворять ли черноту железа
    /// в панели.
    ///
    /// Отличается от `inNotch` ровно одним: режим съёмки здесь не участвует.
    /// Растворение — обычный градиент, он рисуется в снимок как есть, и гасить
    /// его вместе со стеклом значит лишить себя единственного способа
    /// проверить его форму. Первую же правку длины перехода пришлось делать
    /// вслепую: на снимке вырез был сплошь чёрным, потому что съёмка гасила
    /// и то, и другое.
    ///
    /// Настройки человека, в отличие от режима съёмки, слушает: ни выбравший
    /// непрозрачный вырез, ни попросивший систему уменьшить прозрачность
    /// не должны видеть никакого растворения.
    static var notchIsTranslucent: Bool {
        isSupported && Settings.shared.notchLook < LookScale.opaque
            && !MotionPreference.shared.reduceTransparency
    }


    /// Затемнение под всплывающей плашкой подписи.
    ///
    /// Своё, а не от роли, потому что случай единственный в своём роде:
    /// плашка лежит **не** на теле панели, а поверх чего попало — обоев,
    /// чужого окна, светлого документа. Всё остальное стекло приложения
    /// сэмплит собственный чёрный остров, а это — что придётся.
    ///
    /// Без стекла остаётся прежняя почти непрозрачная чернота: 0.92 были
    /// подобраны ровно под эту задачу и своей работы не проваливали.
    /// Со стеклом — меньше, иначе стекла не видно вовсе, но заметно больше,
    /// чем у поверхностей внутри панели: там под стеклом чёрное тело,
    /// а здесь может оказаться белый лист.
    static var hintScrim: Double { inNotch ? scrim(0.58) : 0.92 }

    /// Затемнение под стеклом всей панели.
    ///
    /// Отдельно от затемнения поверхностей: у панели нет роли, но текст
    /// на ней есть — и самый мелкий в приложении. Заголовок в крыле набран
    /// одиннадцатью пунктами, подпись под чёлкой — восемью с половиной,
    /// и лежат они прямо на стекле, без всякой плитки под собой.
    ///
    /// Стало заметнее после того, как чернота начала растворяться ещё
    /// и вбок: крылья с заголовком и кнопками уехали из черноты на стекло.
    ///
    /// Лестница прозрачностей текста в `NotchStyle` посчитана под чёрное —
    /// 0.92 / 0.75 / 0.60 / 0.48 дают там от 17.55:1 до 4.92:1. Это
    /// затемнение возвращает ей то основание, под которое её считали,
    /// не отнимая у панели прозрачности.
    static var panelScrim: Double { GlassLook.current.panelScrim(0.24) }

    /// Чем подменить стекло на снимке.
    ///
    /// Стекло в снимок попадает мусором — неоново-розовым с радужной каймой:
    /// `layer.render(in:)` рисует backdrop без настоящего фона. При плоской
    /// съёмке его место занимает ровная темнота: она не выдаёт себя за стекло,
    /// но и не оставляет панель дырой, сквозь которую видно рабочий стол.
    static let snapshotStandIn: Double = 0.62

    /// Стекло в обычных окнах.
    static var inWindows: Bool {
        isSupported && !isFlatForSnapshot
    }

    // MARK: - Роли
    //
    // Плотность заливки на плоской ветке берётся отсюда, а не по месту.
    // Числа те же, что были: 0.08 в покое у всего, что лежит на теле панели.

    enum Role {
        /// Карточка в раскрытой панели: встреча, задачи, показатель.
        case card
        /// Плитка меню и всего, что нажимают.
        case tile
        /// Строка списка.
        case row
        /// Кнопка со своей подложкой.
        case control
        /// Доля сегментного переключателя.
        ///
        /// В покое не рисует ничего: сегмент показан не собственной
        /// подложкой, а тем, что лежит на общей дорожке. Подложку получает
        /// только выбранный — она и есть бегунок.
        case segment

        /// Заливка на плоской ветке.
        ///
        /// - Parameter lit: под курсором или нажата.
        func fill(lit: Bool) -> Double {
            switch self {
            case .card:
                // Карточку не нажимают — ей и подсвечиваться незачем.
                return NotchStyle.tileFill
            case .tile, .row:
                return lit ? NotchStyle.tileFillHover : NotchStyle.tileFill
            case .control:
                return lit ? NotchButtonStyle.pressedFill : NotchButtonStyle.restingFill
            case .segment:
                // Невыбранный не рисует ничего: его показывает дорожка,
                // на которой он лежит. Своя подложка у каждого превращала
                // переключатель обратно в два отдельных действия.
                return lit ? NotchStyle.tileFillHover : 0
            }
        }

        /// Подсветка **поверх стекла**.
        ///
        /// В покое стекло не нуждается в заливке вовсе — оно и есть подложка.
        /// А вот отклик на курсор оставлен своим, хотя `Glass.interactive`
        /// обещает его сам: обещание проверить из сессии нечем (стекло
        /// не попадает в снимок), а плитка, переставшая отзываться
        /// на наведение, — это возврат к тому, с чего начинали, когда курсор
        /// ходил по мёртвому полю.
        ///
        /// Два отклика друг другу не мешают: свой — заливка, системный —
        /// преломление. Если системный окажется достаточным, этот убирается
        /// одной строкой здесь.
        var litOnGlass: Double {
            switch self {
            // Бегунок сегмента и так тонирован цветом смысла — добавлять
            // ему белизны значит только разбавлять этот цвет.
            case .card, .segment: return 0
            case .tile, .row, .control: return 0.12
            }
        }

        /// Затемнение под стеклом.
        ///
        /// Стекло берёт цвет от обоев, а обои бывают любые. Плитка, у которой
        /// подложка целиком отдана обоям, на светлой картинке становится
        /// светлой — и белая подпись на ней пропадает. Ровно это и случилось
        /// в меню всех функций: плитки перестали читаться.
        ///
        /// Затемнение возвращает подложке собственную плотность, не отнимая
        /// у неё прозрачности: сквозь плитку по-прежнему видно, что под ней,
        /// но она заведомо темнее того, что под ней. Подпись держится
        /// на этом, а не на удаче с обоями.
        ///
        /// У плитки больше, чем у карточки: по плитке читают одно короткое
        /// слово мелким кеглем, и запас ей нужнее.
        var scrimOnGlass: Double { scrimOnGlass(in: .current) }

        /// Затемнение под стеклом при заданном виде стекла: множитель
        /// ползунка затемнения и ослабление на прозрачной стороне ползунка
        /// прозрачности.
        func scrimOnGlass(in look: GlassLook) -> Double {
            look.surfaceScrim(baseScrim)
        }

        private var baseScrim: Double {
            switch self {
            case .tile: return 0.42
            case .row, .control: return 0.30
            case .card: return 0.24
            // Дорожка сегмента и так лежит на затемнённой карточке,
            // а бегунок держится цветом.
            case .segment: return 0
            }
        }

        /// Насколько крепко подмешивать цвет смысла в стекло.
        ///
        /// Не в полную силу. Цвета палитры светлые — мятный, янтарный,
        /// бирюзовый, — и стекло, взявшее их целиком, высветлялось до того,
        /// что белая подпись на нём пропадала. Треть отвечает на «чьё это»,
        /// не отнимая у подписи фона.
        static let tintStrength: Double = 0.32

        /// Отзывается ли поверхность на курсор и нажатие.
        ///
        /// У стекла это своя механика (`Glass.interactive`), а не прибавка
        /// к яркости: оно подсвечивается и слегка подаётся под нажатием само.
        /// Карточка — единственная, кого не нажимают.
        var isInteractive: Bool {
            switch self {
            case .card: return false
            case .tile, .row, .control, .segment: return true
            }
        }
    }
}

// MARK: - Наложение на вид

extension View {
    /// Подложка под содержимым: стекло или заливка.
    ///
    /// - Parameters:
    ///   - role: чем поверхность работает — от неё плотность и отклик.
    ///   - shape: форма подложки. Задаётся снаружи, потому что скругления
    ///     концентричны и считаются от того, во что вложено.
    ///   - tint: цвет смысла — мятный у команд, бирюзовый у буфера. Стекло
    ///     подмешивает его в себя; на плоской ветке цвет остаётся у значка,
    ///     как и был.
    ///   - lit: поверхность под курсором или нажата.
    ///   - glass: рисовать ли стекло. Решение приходит снаружи, а не
    ///     спрашивается здесь: у выреза и у окон оно разное.
    func surface<S: Shape>(
        _ role: Surface.Role,
        in shape: S,
        tint: Color? = nil,
        lit: Bool = false,
        glass: Bool,
        interactive: Bool? = nil
    ) -> some View {
        modifier(SurfaceStyle(
            role: role, shape: shape, tint: tint, lit: lit, glass: glass, interactive: interactive
        ))
    }

    /// Поверхность главного действия: цветное стекло вместо ровной заливки.
    ///
    /// Отдельно от `surface(_:in:tint:lit:glass:)`, потому что там цвет —
    /// оттенок смысла поверх белой подложки, а здесь цвет **и есть** подложка.
    /// Кнопка «Обновить» или «Подключиться» на плашке события — единственное
    /// действие, ради которого плашку и показывают, и стекло ей полагается
    /// не для приличия: рядом стеклянная плашка, и ровная заливка на ней
    /// читается наклейкой.
    ///
    /// Затемнения нет: оно осветляло бы задачу цвета — заявить о себе.
    /// Читаемость подписи держит не подложка, а сам цвет, и считается
    /// подпись по его светлоте.
    func accentSurface<S: Shape>(in shape: S, tint: Color, glass: Bool) -> some View {
        modifier(AccentSurface(shape: shape, tint: tint, glass: glass))
    }

    /// Стекло самой панели — без заливки и без отклика на курсор.
    ///
    /// Отдельно от `surface(_:in:tint:glass:)`, потому что у панели нет роли:
    /// она не плитка и не строка, у неё нет плотности в покое и она не
    /// нажимается. Общий вызов с четырьмя неприменимыми параметрами был бы
    /// не обобщением, а маскировкой.
    func panelGlass<S: Shape>(in shape: S, glass: Bool) -> some View {
        modifier(PanelGlass(shape: shape, glass: glass))
    }
}

/// Наложение подложки.
///
/// Ветвление здесь одно и только по `#available`. Это важно: правило
/// приложения — «что включается и выключается, должно быть значением,
/// а не веткой», потому что разные ветви `if` дают разные типы вида,
/// и SwiftUI пересобирает поддерево вместо того, чтобы доиграть переход.
/// На этом уже ловили отрыв острова от кромки при мурчании.
///
/// Доступность системы за время работы не меняется ни разу, поэтому её ветка
/// безопасна. А выбор человека и режим съёмки меняются на ходу — и они
/// проведены **значениями**: `Glass.identity` вместо ветки «без стекла»
/// и прозрачность заливки вместо ветки «без заливки».
private struct SurfaceStyle<S: Shape>: ViewModifier {
    let role: Surface.Role
    let shape: S
    let tint: Color?
    let lit: Bool
    let glass: Bool
    /// Отклик стекла на курсор. По умолчанию — от роли; задаётся отдельно,
    /// когда плотность нужна плиточная, а нажимается не сама поверхность,
    /// а кнопки на ней — как у плитки быстрых команд.
    var interactive: Bool?
    @Environment(\.glassLook) private var look

    /// Под стеклом заливка гаснет — остаётся только подсветка под курсором.
    /// Гаснет, а не убирается: убрать значило бы завести ветку.
    private var fill: Double {
        glass ? (lit ? role.litOnGlass : 0) : role.fill(lit: lit)
    }

    /// Затемнение под стеклом. Вне стекла нулевое: там подложка и так
    /// лежит на чёрном теле панели.
    private var scrim: Double {
        glass ? role.scrimOnGlass(in: look) : 0
    }

    func body(content: Content) -> some View {
        if #available(macOS 26.0, *) {
            content
                .background(shape.fill(.black.opacity(scrim)))
                .background(shape.fill(.white.opacity(fill)))
                .glassEffect(glassValue, in: shape)
        } else {
            content
                .background(shape.fill(.white.opacity(fill)))
        }
    }

    @available(macOS 26.0, *)
    private var glassValue: Glass {
        guard glass else { return .identity }
        var value = Glass.regular
        // Цвет подмешивается вполсилы: взятый целиком, он высветлял стекло
        // до того, что подпись на нём пропадала.
        if let tint { value = value.tint(tint.opacity(Surface.Role.tintStrength)) }
        return value.interactive(interactive ?? role.isInteractive)
    }
}

/// Группа стеклянных поверхностей.
///
/// То, ради чего Liquid Glass вообще существует: соседние стеклянные
/// поверхности внутри группы сливаются и растекаются друг в друга по мере
/// сближения, а не лежат стопкой отдельных матовых прямоугольников. Без
/// группы шесть плиток меню — шесть осколков.
///
/// Обёртка, а не голый `GlassEffectContainer`, потому что доступен он
/// с macOS 26, а вёрстка одна на все версии. Ниже группа не делает ничего
/// и содержимое проходит насквозь.
struct GlassGroup<Content: View>: View {
    /// С какого расстояния поверхности начинают тянуться друг к другу.
    var spacing: CGFloat?
    @ViewBuilder var content: () -> Content

    var body: some View {
        if #available(macOS 26.0, *) {
            GlassEffectContainer(spacing: spacing) { content() }
                // Появляясь и пропадая, поверхности внутри группы перетекают
                // друг в друга, а не возникают на месте.
                //
                // Это и есть то, ради чего затевался общий пространственный
                // переход. Перетекание **между** разными накладками — буфер
                // в полку, полка в таймер — оказалось не тем, чем казалось:
                // сопоставление требует пар, а пары там нет. Строке истории
                // буфера не отвечает ни одна плитка полки, и склеивать их
                // значило бы выдумать связь, которой в приложении нет.
                //
                // А внутри группы содержимое меняется постоянно, и пары там
                // естественные: список команд сменяется списком моделей,
                // кнопки оформления приходят и уходят вместе с режимом
                // заметки, плитки меню гаснут вслед за настройками.
                .glassEffectTransition(.matchedGeometry)
        } else {
            content()
        }
    }
}

/// Подложка главного действия.
///
/// Цвет остаётся заливкой **под** стеклом, а не уходит в один лишь тинт.
/// Тинтом он зависел бы от того, что под плашкой: мятная кнопка над светлыми
/// обоями вышла бы бледной, над тёмными — густой, а подпись на ней считается
/// по светлоте цвета один раз и на все случаи. Заливка держит цвет тем самым,
/// по которому подпись и подобрана, а стекло добавляет к нему преломление
/// и отклик на нажатие.
private struct AccentSurface<S: Shape>: ViewModifier {
    let shape: S
    let tint: Color
    let glass: Bool
    @Environment(\.glassLook) private var look

    /// Под стеклом цвет ложится вполсилы, без него — целиком: просвечивать
    /// нечему, и ослабленный цвет был бы просто бледным.
    private var fillOpacity: Double { glass ? look.accentFill : 1 }

    func body(content: Content) -> some View {
        if #available(macOS 26.0, *) {
            content
                .background(shape.fill(tint.opacity(fillOpacity)))
                .glassEffect(glass ? .regular.tint(tint).interactive() : .identity, in: shape)
        } else {
            content.background(shape.fill(tint))
        }
    }
}

/// Стекло панели: одна поверхность на всю форму выреза.
///
/// Отклика на курсор нет намеренно. `Glass.interactive` подсвечивает
/// поверхность под указателем — у кнопки это отклик, у панели, над которой
/// курсор стоит **всё время, пока она открыта**, это была бы постоянно
/// подсвеченная панель.
///
/// Прозрачность (`Surface.frost`): матовое гаснет по ползунку, а под ним
/// проступает линза `LensGlass`. Ступеней у системы
/// всего две (`.regular` и `.clear`), а ползунок обещает плавный ход.
/// В крайних точках остаётся одно стекло — матовое по умолчанию рисуется
/// ровно как прежде.
private struct PanelGlass<S: Shape>: ViewModifier {
    let shape: S
    let glass: Bool
    /// Из среды, а не чтением настройки в `body`: модификатор с теми же
    /// входами SwiftUI не пересчитывает, и ползунок не менял ничего.
    @Environment(\.glassLook) private var look

    func body(content: Content) -> some View {
        if #available(macOS 26.0, *) {
            let frost = look.frost
            let blended = glass && frost > 0 && frost < 1
            // Прозрачное стекло — не здесь: системное `.clear` на macOS
            // размывает не меньше матового (проверено снимком), и под
            // прозрачной половиной ползунка лежит `LensGlass` из `NotchView`.
            // Здесь матовое только гаснет.
            content
                .glassEffect(glass && frost >= 1 ? .regular : .identity, in: shape)
                .background(
                    Color.clear
                        .glassEffect(blended ? .regular : .identity, in: shape)
                        .opacity(blended ? frost : 0)
                )
        } else {
            content
        }
    }
}

private struct GlassLookKey: EnvironmentKey {
    static var defaultValue: Surface.GlassLook { .outsideNotch }
}

extension EnvironmentValues {
    /// Вид стекла выреза. Ставит `NotchView`; вне выреза — матовое.
    var glassLook: Surface.GlassLook {
        get { self[GlassLookKey.self] }
        set { self[GlassLookKey.self] = newValue }
    }
}

/// Прозрачное стекло с линзой по краю — как у системных виджетов поверх
/// обоев: то, что за ним, остаётся резким, а у кромки преломляется.
///
/// SwiftUI такого не даёт: у `Glass` два вида, и оба на macOS размывают
/// (`.clear` даже сильнее). Нужный вид — у `NSGlassEffectView` среди
/// закрытых вариантов (`_variant`). Перебор всех 24 снимком: 11 — резкий
/// фон и линза с цветной каймой, 20 — то же мягче, 13–15 — почти ничего.
/// Нет варианта — остаётся обычный стиль `.clear`, пусть и размытый.
///
/// Форму задаёт только `cornerRadius`: маска слоя линзу ломает —
/// преломление идёт по прямоугольнику, а не по скруглению.
@available(macOS 26.0, *)
struct LensGlass: NSViewRepresentable {
    var cornerRadius: CGFloat

    static let variant = 11

    func makeNSView(context: Context) -> NSGlassEffectView {
        let view = NSGlassEffectView()
        view.style = .clear
        if view.responds(to: NSSelectorFromString("set_variant:")) {
            view.setValue(Self.variant, forKey: "_variant")
        }
        view.cornerRadius = cornerRadius
        return view
    }

    func updateNSView(_ view: NSGlassEffectView, context: Context) {
        if view.cornerRadius != cornerRadius { view.cornerRadius = cornerRadius }
    }
}

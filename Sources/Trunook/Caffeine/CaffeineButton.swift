import SwiftUI

/// Чашка кофе в левом крыле раскрытой панели: не давать экрану гаснуть.
///
/// Рядом с погодой, а не среди кнопок справа, и это не про симметрию. Справа
/// живут действия — «спросить модель», «настройки», — которые что-то открывают
/// и заканчиваются. Чашка не действие, а состояние, и стоять ей рядом
/// со сведениями о мире, где стоит погода.
///
/// Включённость показана **подложкой с обводкой**, а не сменой значка. Значок
/// в одиннадцать пунктов человек не сличает по памяти — залитая чашка от пустой
/// отличается не сразу, — а появившаяся под ней рамка видна боковым зрением.
///
/// Нажатие не переключает удержание, а открывает выбор срока: см.
/// `CaffeinePanel`. Переключение вслепую не давало узнать, надолго ли
/// включилось, — а чашку включают под дело, и срок у каждого дела свой.
struct CaffeineButton: View {
    let isOn: Bool
    let action: () -> Void

    /// Было 20 — меньше нормы в 24 точки. Значок остаётся
    /// в одиннадцать пунктов, растёт только область нажатия.
    private static let side: CGFloat = NotchPanelButton.size

    var body: some View {
        Button(action: action) {
            // Значок один и тот же в обоих состояниях: контурная чашка
            // в одиннадцать пунктов от залитой почти неотличима, а разницу
            // и должна показывать подложка, а не подмена глифа.
            Image(systemName: "cup.and.saucer.fill")
                .font(.system(size: NotchStyle.font(11), weight: .medium))
                .foregroundStyle(isOn ? Palette.caffeine : .white.opacity(NotchStyle.secondaryOpacity))
                .frame(width: Self.side, height: Self.side)
                .background(shape.fill(isOn ? Palette.caffeine.opacity(0.2) : .clear))
                // Обводка, а не более плотная заливка.
                //
                // Подложка в 0.2 давала 1.41:1 к чёрному при норме 3:1
                // для признака состояния. Взять норму одной заливкой можно
                // было бы только выше 0.45, но это уже сплошной оранжевый
                // прямоугольник в чёлке: включённая чашка кричала бы громче
                // всей панели. Обводка тем же цветом на полной насыщенности
                // даёт 12.22:1 — вчетверо больше нормы — и остаётся тонкой.
                .overlay(shape.strokeBorder(isOn ? Palette.caffeine : .clear, lineWidth: 1))
                // Без этого нажимается только сама чашка: подложка нарисована
                // фоном, а метка кнопки о ней не знает и остаётся прозрачной
                // для попаданий.
                .contentShape(shape)
        }
        .buttonStyle(PressableStyle())
        // Имя постоянное, состояние — отдельным значением. Раньше имя было
        // одним на оба состояния и о включённости не говорило вовсе: диктор
        // читал «не давать экрану гаснуть» и когда экран уже не гас,
        // и когда гас, — то есть не отвечал на единственный вопрос,
        // который к этой кнопке вообще есть.
        //
        // Имя совпадает с названием панели, которую кнопка открывает: так
        // человек слышит, куда попадёт, ещё до нажатия.
        .notchHint(
            t("Бодрость"),
            bubble: isOn ? t("Экран не гаснет — нажмите, чтобы выбрать срок")
                         : t("Не давать экрану гаснуть — выбрать срок")
        )
        .accessibilityValue(isOn ? t("включено") : t("выключено"))
        .accessibilityAddTraits(isOn ? .isSelected : [])
        .animation(.easeOut(duration: 0.15), value: isOn)
    }

    private var shape: RoundedRectangle {
        RoundedRectangle(cornerRadius: NotchStyle.rowRadius, style: .continuous)
    }
}

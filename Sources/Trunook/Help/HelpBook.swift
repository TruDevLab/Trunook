/// Одна тема справки о самом приложении.
///
/// Собственным списком, а не пересказом README: README написан для чтения
/// глазами — абзацами и без «где это включить», — а модели нужен короткий
/// ответ с названием раздела настроек. Раздел при этом не выписан словом,
/// а взят из самой вкладки настроек: переименуют её — переименуется и ответ.
struct HelpTopic: Identifiable, Equatable {
    /// Постоянное имя темы. Не переводится: по нему тему находят тесты
    /// и журнал, а человеку показывается заголовок.
    let id: String
    let title: String
    /// Раздел настроек, где это включают. `nil` — включать нечего.
    let tab: SettingsSelection.Tab?
    /// Что это и как этим пользоваться — две-три фразы.
    let text: String
    /// Слова, по которым тему ищут: синонимы и то, чего нет в заголовке.
    ///
    /// Переводятся вместе со всем остальным: вопрос задают на языке
    /// интерфейса, и русские слова в английском окне не нашли бы ничего.
    let keywords: String

    /// Готовый ответ модели: тема, суть и куда идти настраивать.
    var answer: String {
        var out = "«\(title)». \(text)"
        if let tab {
            out += " " + tf("Раздел настроек: «%@».", tab.title)
        }
        return out
    }
}


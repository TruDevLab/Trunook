    static func topic(id: String) -> HelpTopic? {
        topics.first { $0.id == id }
    }

    /// Ответ на вопрос, под который темы не нашлось: о чём вообще можно
    /// спросить. Не пустота: модель, получив «ничего нет», отвечает
    /// выдумкой — а получив оглавление, переспрашивает по делу.
    static func contents() -> String {
        let titles = topics.dropFirst().map { "«\($0.title)»" }.joined(separator: ", ")
        let overview = topic(id: "overview")?.text ?? ""
        return overview + "\n\n" + tf("О чём ещё можно спросить: %@.", titles)
    }
}

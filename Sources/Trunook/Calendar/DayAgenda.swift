import Foundation

/// Какое из дел дня — ближайшее.
///
/// Отдельно от вёрстки и без обращений к SwiftUI: «ближайшее» — это правило,
/// а не рисунок, и у него больше краёв, чем кажется. Прошедшие, идущее прямо
/// сейчас, дела на весь день, чужой день вместо сегодняшнего — каждый край
/// проверяется тестом, а не тем, что человек однажды посмотрел на список
/// в неудачную минуту.
enum DayAgenda {
    /// Номер строки, которую надо выделить. `nil` — выделять нечего.
    ///
    /// Правила три, и все три из одного соображения: выделение отвечает
    /// на вопрос «куда мне сейчас», а не «что тут вообще есть».
    ///
    /// 1. **Только сегодня.** В списке будущего дня ближайшего нет: там
    ///    впереди всё, и пометка на первой строке значила бы просто «первая».
    ///    В прошедшем дне — тем более.
    /// 2. **Идущее прямо сейчас важнее ещё не начавшегося.** Встреча,
    ///    которая идёт, и есть то, куда человеку сейчас; помечать вместо неё
    ///    следующую значило бы торопить его мимо текущей.
    /// 3. **Дела на весь день не в счёт.** У них нет часа, они стоят первыми
    ///    в списке, и «ближайшим» такое дело было бы весь день подряд.
    static func nextIndex(
        in items: [CalendarItem],
        now: Date = Date(),
        calendar: Calendar = .current
    ) -> Int? {
        items.firstIndex { item in
            guard !item.isAllDay else { return false }
            guard calendar.isDate(item.start, inSameDayAs: now) else { return false }
            // Конец, а не начало: пока встреча идёт, ближайшее — она сама.
            // У записи без конца (напоминание) им считается само начало.
            let finishes = item.end ?? item.start
            return finishes > now
        }
    }

    /// Подпись у выделенной строки: «идёт» или «через 40 мин».
    ///
    /// Отсчёт берётся тот же, что и у полоски в чёлке, — но со словом
    /// «через»: в полоске его нет, потому что каждое лишнее слово раздвигает
    /// остров в обе стороны сразу, а здесь ширины сколько угодно, и голое
    /// «40 мин» читалось бы длительностью встречи, а не временем до неё.
    static func badge(for item: CalendarItem, now: Date = Date()) -> String {
        item.start <= now ? t("идёт") : tf("через %@", item.countdown(from: now))
    }
}

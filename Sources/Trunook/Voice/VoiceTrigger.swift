import AppKit

/// Чем зовут голосового ассистента: модификатор, нажатый дважды подряд.
///
/// Не `HotKeySpec`, и это не упрощение, а другой род вызова. Сочетание там —
/// модификаторы **плюс клавиша**, и `RegisterEventHotKey` иначе не умеет.
/// Здесь клавиши нет вовсе: жест целиком состоит из модификатора, нажатого
/// и отпущенного два раза.
///
/// Ради чего: короче уже некуда, и — в отличие от любого короткого
/// сочетания — жест **ничего не отбирает у набора текста**. ⌥Space перестал
/// бы вставлять неразрывный пробел, ⌥A — печатать «å», а модификатор сам
/// по себе не печатает ничего. Тот же жест, которым система зовёт свою
/// диктовку двойным Fn.
///
/// Цена — вызов идёт мимо Carbon, глобальным монитором событий, а тот
/// требует Универсального доступа и молчит, пока открыто меню чужого
/// приложения. Подробности в `DoubleTapModifier`.
///
/// **⇧ в списке нет намеренно.** Две заглавные буквы подряд — обычный набор,
/// а не жест: «ББ» в начале слова звало бы ассистента.
enum VoiceTrigger: String, CaseIterable, Identifiable {
    case control
    case option
    case command
    case off

    var id: String { rawValue }

    /// Какой модификатор ждём. `nil` — вызов выключен.
    var flag: NSEvent.ModifierFlags? {
        switch self {
        case .control: return .control
        case .option: return .option
        case .command: return .command
        case .off: return nil
        }
    }

    /// Подпись в настройках: сам жест, а не его название. Двойной значок
    /// читается как «дважды» без единого слова и одинаково на всех языках.
    var title: String {
        switch self {
        case .control: return "⌃⌃"
        case .option: return "⌥⌥"
        case .command: return "⌘⌘"
        case .off: return t("Выключен")
        }
    }
}

import CoreGraphics
import Foundation

/// Размеры, общие для всех панелей выреза.
///
/// Раньше каждое число подбиралось по месту и по месту же оставалось:
/// скругления 8, 9, 10 и 22 точки, высоты строк 26, 34, 66 и 78, поля 6, 8,
/// 11, 12 и 16. Пока панелей было три, это не мешало; на седьмой панели
/// подбирать числа заново стало дороже, чем договориться один раз.
///
/// Смысл не в единообразии ради единообразия: новая панель должна вставать
/// в общий ритм сама, без сверки со снимками соседних.
enum NotchStyle {
    /// Отступ содержимого от краёв панели по горизонтали.
    static var panelPadding: CGFloat { scaled(16) }

    /// Вогнутое плечо формы: на столько чёрное тело панели у́же её рамки
    /// с каждой стороны.
    ///
    /// `NotchShape` уводит верхние уголки наружу — переход к кромке экрана
    /// рисуется вогнутым, и тело начинается не от края рамки, а на столько
    /// точек внутрь. Поле, отмеренное от рамки, на этом плече и кончается:
    /// в панели ответа модели шестнадцать точек превращались в четыре,
    /// и строка ввода липла к кромке, хотя снизу отступ был впятеро больше.
    static let shoulderInset: CGFloat = 12
    /// Между чёлкой и первой строкой содержимого.
    static var topGap: CGFloat { scaled(8) }
    /// Под последней строкой.
    static var bottomPadding: CGFloat { scaled(12) }

    /// Поле содержимого от края **рамки**, когда отмерять его надо от чёрного
    /// тела. Тело у́же рамки на вогнутое плечо с каждой стороны, поэтому
    /// к полю прибавляется оно.
    ///
    /// Отсюда берут число все панели, которым нужны одинаковые зазоры со всех
    /// сторон: поле, отмеренное от рамки, на плече и кончается — шестнадцать
    /// точек сбоку превращались в четыре при двенадцати снизу.
    static var bodyInset: CGFloat { bottomPadding + shoulderInset }

    // MARK: Размер текста
    //
    // Все кегли и все размеры, которые под них подогнаны, проходят через один
    // множитель. Порознь их не масштабировать: строка, выросшая в подложке
    // прежней высоты, обрезается снизу, — а сходятся кегль и высота строки
    // только если растут вместе.

    /// Во сколько раз крупнее обычного рисовать текст в вырезе.
    ///
    /// Всегда единица. Настройка размера текста до выреза не доходит вовсе
    /// и доходить не должна.
    ///
    /// Сначала масштаб ограничили полутора: панели растут вширь вместе
    /// с текстом, а ширину им отпускать некуда — вырез прибит к верхней
    /// кромке экрана. Полтора казались тем запасом, который экран стерпит.
    ///
    /// Не стерпел. Ширина панели — не единственное, что упирается: под чёлкой
    /// остаётся ровно столько места, сколько оставила аппаратная вырезка,
    /// и на пятнадцати пунктах вместо десяти строка в крыле лезет на саму
    /// чёлку, а плитки в раскрытой панели встают в два ряда вместо одного.
    /// Проверять это на каждой модели с её собственной шириной выреза —
    /// работа, которую нельзя доделать: моделей больше, чем машин под рукой.
    ///
    /// Поэтому средство изменить размер текста осталось там, где растить
    /// нечему помешать, — в окне настроек и в окне знакомства. Оба обычные
    /// окна, оба тянутся мышью, оба отдают все двести процентов, которых
    /// требует критерий доступности. Критерий выполнен приложением; вырез
    /// в нём не участвует, как не участвует в нём строка меню.
    ///
    /// Единица возвращается отсюда, а не вырезается из ста тридцати восьми
    /// вызовов `scaled` и `font`: так решение остаётся в одном месте
    /// и читается вместе с причиной.
    static var textScale: CGFloat { 1 }

    /// Размер, подогнанный под кегль: высота строки, сторона кнопки, поле.
    /// Округляется — это точки на экране, и половина точки в раме оборачивается
    /// размытым краем.
    static func scaled(_ value: CGFloat) -> CGFloat {
        (value * textScale).rounded()
    }

    /// Кегль. В отличие от размеров, **не** округляется.
    ///
    /// Округление стоило целой ступени, и не на краю шкалы, а на обеих
    /// увеличенных настройках сразу. Шапка панели набрана одиннадцатью,
    /// строка списка — одиннадцатью с половиной; на ста двадцати пяти
    /// процентах это 13.75 и 14.375, и обе округлялись в четырнадцать.
    /// На ста пятидесяти — 16.5 и 17.25, обе в семнадцать.
    ///
    /// То есть разница между заголовком и строкой под ним пропадала ровно
    /// у тех, кто текст увеличил, — у тех единственных, кому она нужнее
    /// всего. Половина пункта в кегле законна, её отрисует сглаживание;
    /// округлять надо рамы, а не буквы.
    ///
    /// Проверку на схлопывание держит `NotchStyleTests.лестницаНеСхлопывается`
    /// — на каждой ступени настройки, а не только на ста процентах.
    static func font(_ value: CGFloat) -> CGFloat {
        value * textScale
    }

    // MARK: Начертание значков
    //
    // Правило одно на приложение, и оно записано здесь потому, что до этого
    // его не было нигде — а начертание всё равно выбиралось, только наугад.
    // Свод по коду показал, что выбиралось оно почти верно: буфер, полка
    // и меню функций стоят залитыми в плитках и в разделах настроек,
    // а в шапках своих панелей — контурными. Почти — потому что чашка
    // делала ровно наоборот, и заметить это можно было, лишь собрав все
    // значки разом.
    //
    // **Залитый** — там, где значок опознаёт предмет и стоит один: плитка
    // меню функций, плитка раздела настроек, значок плашки события, плитка
    // окна знакомства. Опереться ему не на что, кроме себя, и плотная форма
    // читается на двадцати точках вернее контурной.
    //
    // **Контурный** — там, где значок сопровождает подпись: шапка панели,
    // кнопка крыла, заголовок карточки настроек. Рядом есть слово, узнавание
    // держится на нём, а значку остаётся не спорить с текстом по весу.
    //
    // У части символов залитого варианта нет вовсе (`timer`, `sparkles`,
    // `text.alignleft`, `gauge…`) — они стоят как есть в обоих положениях,
    // и это не нарушение: правило про выбор, а выбора там не предлагают.

    /// Шапка панели: значок, название, действия справа.
    static var headerHeight: CGFloat { scaled(26) }

    /// Отступ содержимого крыла от самой чёлки: вплотную к ней подпись
    /// читается как часть аппаратного выреза, а не как заголовок панели.
    ///
    /// Живёт здесь, а не в `NotchPanel`, потому что от него зависит ширина
    /// крыла — а её панели теперь считают, чтобы ряд кнопок в шапке
    /// гарантированно поместился.
    static let notchInset: CGFloat = 10

    /// Ширина ряда кнопок в крыле.
    ///
    /// - Parameter reserved: место под то, что стоит в крыле рядом
    ///   с кнопками, — счётчик записей или подсказку клавиш.
    static func wingRow(buttons: Int, spacing: CGFloat = 2, reserved: CGFloat = 0) -> CGFloat {
        let row = CGFloat(buttons) * NotchPanelButton.size
            + CGFloat(max(0, buttons - 1)) * spacing
        return reserved > 0 ? reserved + spacing + row : row
    }

    /// Наименьшая ширина панели, при которой в крыле помещается `wing`.
    ///
    /// Обратный ход к расчёту крыла в `NotchPanel`: там из ширины панели
    /// выводится крыло, здесь из крыла — ширина. Выписывать её числом нельзя:
    /// крыло зависит от ширины чёлки, а та у каждой модели своя, и подобранное
    /// на одной машине число на другой обрезало бы последнюю кнопку.
    static func width(fittingWing wing: CGFloat, notchWidth: CGFloat, bodyPadding: CGFloat) -> CGFloat {
        2 * (wing + bodyPadding + shoulderInset + notchInset) + notchWidth
    }

    // MARK: Высота строки списка
    //
    // Две ступени вместо пяти. Было 26 у команд, 28 у таймера и чашки,
    // 34 у буфера, 40 у заметок — один и тот же по смыслу предмет,
    // «строка списка», выражался четырьмя числами, и ни одно из них
    // не знало об остальных. Свод по коду это и показал: числа сведены
    // каждое в свой файл, но между собой не связаны ничем.
    //
    // Ступеней ровно столько, сколько бывает содержания: одна строка текста
    // или две — заголовок с подписью. Третьей не нужно, а пятой не бывает.

    /// Строка в одну строку текста: команда, срок таймера, запись буфера.
    static var rowHeight: CGFloat { scaled(28) }

    /// Строка в две: заголовок и подпись под ним — как у заметки.
    ///
    /// Не вдвое выше: подпись набрана мельче заголовка, и двойной запас
    /// оставил бы в строке пустоту.
    static var rowHeightDouble: CGFloat { scaled(40) }

    /// Шаг между плитками и строками.
    static var gridSpacing: CGFloat { scaled(8) }
    /// Между подложками раскрытой панели — он же единственный разделитель
    /// между ними. Тесней шага между строками: подложки и так разведены
    /// собственными полями.
    static var cardGap: CGFloat { scaled(6) }
    /// Между строками списка теснее, чем между плитками: строки читаются
    /// подряд, а плитки — по отдельности.
    static var rowSpacing: CGFloat { scaled(3) }

    // MARK: Скругления
    //
    // Все подложки скругляются непрерывной кривой (`style: .continuous`),
    // а не дугой окружности. Это не вкусовщина: сам вырез нарисован
    // квадратичными кривыми (см. `NotchShape`), и непрерывное скругление —
    // ближайшее, что есть в SwiftUI. Дуга рядом с ним читается острее,
    // и подложка выглядит вырезанной из другого приложения.
    //
    // Числа тоже сведены сюда. Раньше по месту стояли 3, 4, 5, 8, 10 и 12,
    // и одинаковые по смыслу подложки — обложка трека в мини-виде и она же
    // в плашке — скруглялись по-разному.

    /// На сколько точек чернота железа растворяется в стекле панели.
    ///
    /// Полоса высотой с аппаратную вырезку остаётся непрозрачно чёрной:
    /// там остров неотличим от самой вырезки, и стекло на этом месте
    /// показало бы обои сквозь железо. Ниже начинается панель — и переход
    /// между одним и другим не должен быть чертой.
    ///
    /// Было двенадцать — и читалось именно чертой. Двенадцать точек это
    /// полстроки текста: на таком расстоянии чернота не растворяется,
    /// а обрывается. Семьдесят два — примерно треть высоты раскрытой
    /// панели, и переход перестаёт быть событием.
    ///
    /// Длинный переход выгоден дважды: первая строка содержимого
    /// (она начинается через `topGap`, то есть через восемь точек после
    /// чёлки) оказывается ещё на почти чёрном, и читается так же, как
    /// читалась до всякого стекла.
    static let ironFade: CGFloat = 72

    /// На сколько точек сплошная чернота выходит **за** аппаратную вырезку,
    /// прежде чем начать растворяться.
    ///
    /// Без этого запаса растворение начиналось ровно на кромке вырезки, и уже
    /// в нескольких точках от неё чернота теряла плотность. Глазом это читалось
    /// так, будто тёмное у́же самой чёлки: физическая вырезка чёрная наглухо,
    /// а рядом с ней остров уже подсвечен — и граница между ними видна.
    ///
    /// Запас переносит начало растворения наружу. Вырезка и полоса вокруг неё
    /// остаются одинаково чёрными, шва между железом и островом нет,
    /// а растворяться начинает то, что и так за пределами железа.
    static let ironBleed: CGFloat = 16

    /// Высота полосы по верхней кромке, которую боковое растворение не трогает.
    ///
    /// Верхними уголками — вогнутыми плечами `NotchShape` — остров держится
    /// за кромку экрана. Боковое растворение съедало их первыми: остров
    /// отрывался от кромки и повисал, а держаться ему полагается именно там.
    ///
    /// Полоса идёт во всю ширину, а не двумя пятнами по углам: между пятнами
    /// и чёрным ядром осталась бы посветлевшая прореха, и верх читался бы
    /// полосатым.
    static let ironAttach: CGFloat = 14

    /// Какую долю своего роста фигура отдаёт полосе крепления, если четырнадцать
    /// точек для неё много.
    ///
    /// Полоска таймера немногим выше самой чёлки, и полоса в четырнадцать точек
    /// плюс растворение под ней съедали её целиком: стекла не оставалось вовсе,
    /// полоска снова становилась чёрным прямоугольником. Доля не даёт полосе
    /// разрастись там, где расти не во что.
    static let ironAttachShare: CGFloat = 0.2

    /// Какую долю роста полоса крепления не переступает **вместе
    /// с растворением под ней**.
    ///
    /// Полоска отсчёта немногим выше чёлки, и полоса плюс её растворение
    /// на такой высоте закрывали всё: полоска снова становилась чёрным
    /// прямоугольником, а стекло у неё пропадало вовсе. Потолок оставляет
    /// нижнюю часть стеклу при любом росте.
    static let ironAttachCeiling: CGFloat = 0.55

    /// То же вбок: на сколько точек чернота растворяется от края чёлки
    /// к краю панели.
    ///
    /// Одной вертикали мало. Панель втрое шире аппаратной вырезки, и без
    /// растворения вбок чёрная полоса шла во всю ширину — то есть железо
    /// как бы расширялось на два крыла, которых у него нет. Растворение
    /// от самой чёлки даёт то, ради чего всё и затевалось: остров вытекает
    /// из вырезки во все стороны, а не выпадает из-под чёрной планки.
    ///
    /// Больше вертикального: крыло шире, чем высок переход вниз, и на нём
    /// есть где растворяться.
    static let ironFadeX: CGFloat = 88

    /// Ступени растворения черноты.
    ///
    /// Не две точки, а кривая. Линейный переход от чёрного к прозрачному
    /// глаз видит полосой: яркость растёт равномерно, а воспринимается
    /// она нелинейно, и середина такого перехода выглядит краем.
    ///
    /// Значения — сглаженный шаг (`smoothstep`): у обоих концов кривая
    /// прижимается к горизонтали, и ни начало растворения, ни его конец
    /// не имеют заметного места.
    static let ironCurve: [Double] = [1, 0.985, 0.94, 0.85, 0.72, 0.55, 0.37, 0.21, 0.09, 0.02, 0]

    /// Нижние углы самой панели.
    static let panelRadius: CGFloat = 22
    /// Подложка карточки в раскрытой панели: встреча, задачи.
    static let cardRadius: CGFloat = 12
    /// Скругление плитки внутри панели.
    static let tileRadius: CGFloat = 9
    /// Скругление строки списка.
    static let rowRadius: CGFloat = 8
    /// Обложки, миниатюры и прочая мелочь внутри строк.
    static let artRadius: CGFloat = 5

    /// Подложка плитки и строки — та же плотность, что у круглых кнопок:
    /// они лежат рядом, и разная читалась как небрежность.
    static var tileFill: Double { NotchButtonStyle.restingFill }
    /// Она же под курсором.
    static var tileFillHover: Double { dense(0.15) }

    // MARK: Уменьшение прозрачности
    //
    // Почти вся иерархия здесь построена на полупрозрачном белом, и системная
    // настройка «Уменьшить прозрачность» ровно про это: кому полупрозрачные
    // слои читать трудно, тому нужны плотные. Настройку читает
    // `MotionPreference`; здесь только пересчёт.
    //
    // Значения вычисляемые, а не постоянные, потому что настройку меняют
    // на ходу. Перерисовку обеспечивают виды, наблюдающие `MotionPreference`:
    // от корня выреза и окна настроек она расходится по всему поддереву.

    /// Насколько плотнее рисовать при уменьшенной прозрачности.
    ///
    /// Не «прибавить столько-то»: у ступени в 0.08 и ступени в 0.60 прибавка
    /// одного размера означала бы совсем разное. Доля от того, что осталось
    /// до непрозрачного, сохраняет между ступенями их отношение.
    private static let densifyShare: Double = 0.35

    static func dense(_ value: Double) -> Double {
        guard MotionPreference.shared.reduceTransparency else { return value }
        return min(1, value + (1 - value) * densifyShare)
    }

    // MARK: Прозрачности текста
    //
    // Четыре ступени вместо десятка случайных значений: заголовок, основной
    // текст, подпись, служебное.
    //
    // Все четыре несут текст, поэтому все четыре обязаны дать его прочесть.
    // На чёрном теле панели порог WCAG в 4.5:1 приходится на прозрачность
    // около 0.46 — ниже неё текста быть не может вовсе. Нижние две ступени
    // лежали ниже: 0.45 давала 4.41:1, а 0.3 — 2.46:1, то есть вдвое меньше
    // нормы и меньше даже порога 3:1 для нетекстовых элементов. Обиднее
    // всего это выходило потому, что набраны ими самые мелкие строки
    // в приложении — от 8.5 до 11 пунктов, — где запас нужен больше всего.
    //
    // Весь текст, стало быть, живёт в полосе от 0.46 до 0.92, и четыре
    // ступени разложены по ней ровно. Побочная выгода: шаги вышли
    // одинаковыми — ×0.82, ×0.80, ×0.80 против прежних ×0.82, ×0.60, ×0.67.
    // Лестница, задуманная как правильная, наконец такой и стала.

    /// 17.55:1 на чёрном.
    static var primaryOpacity: Double { dense(0.92) }
    /// 11.45:1.
    static var titleOpacity: Double { dense(0.75) }
    /// 7.37:1. Было 0.45 — 4.41:1, недобор.
    static var secondaryOpacity: Double { dense(0.60) }

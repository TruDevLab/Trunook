import SwiftUI

/// Подпись значка: та, что произносит диктор, и та, что видит глаз.
///
/// Кнопки в шапках панелей — одни значки без слов, и это не небрежность:
/// крылья по бокам от чёлки узкие, подпись под каждым значком туда не встанет,
/// а ужатую до размера, который влезет, читать будет нечем.
///
/// Отсюда раньше делался вывод, что подписи нет вообще. Он неверен дважды.
///
/// Во-первых, имя для дерева доступности не занимает на экране ни точки:
/// это строка, которую произносит VoiceOver, и место она отнимает только
/// в памяти. Не иметь её незачем ни при какой тесноте.
///
/// Во-вторых, глазу подпись тоже можно показать — не под значком, а под всей
/// чёлкой. Там пусто в любом состоянии выреза, и туда влезает целая фраза,
/// а не одно слово в восемь пунктов.
///
/// Обе берутся из одной строки, поэтому разойтись им негде.
enum NotchHintLayout {
    /// Высота плашки. Задана числом, а не выведена из содержимого: на неё
    /// закладывается высота окна, а «примерно столько» плашку обрежет.
    static var height: CGFloat { NotchStyle.scaled(22) }

    /// Зазор между низом панели и плашкой. Вплотную она читается как нижний
    /// край самой панели, а не как отдельная подсказка.
    static let gap: CGFloat = 7

    /// Сколько места под панелью держит окно.
    static var reserved: CGFloat { height + gap }
}

/// Подпись какого значка показывать прямо сейчас.
///
/// Устроен как `HoverTracker` и по той же причине: `@State` в этом тулчейне
/// недоступен, держать признак наведения внутри самой кнопки нечем. Общий
/// на всё приложение — вырез один, и значок под курсором в нём тоже один.
final class NotchHintTracker: ObservableObject {
    static let shared = NotchHintTracker()

    /// Подпись того, на что наведён курсор.
    @Published private(set) var hovered: String?

    /// Подпись того, что подсвечено с клавиатуры.
    ///
    /// Отдельно от наведения, потому что это два разных указателя, и оба
    /// бывают одновременно: курсор лежит где-то в панели, а стрелками ведут
    /// подсветку совсем по другому. Раньше источник был один — наведение, —
    /// и подсказка к кнопке, выбранной клавишей, не показывалась вовсе:
    /// человек водил подсветку по трём одинаковым кружкам, не зная, какой
    /// из них что делает.
    @Published private(set) var focused: String?

    /// Что показывать. Клавиатура важнее курсора: подсветку ведут нарочно,
    /// а курсор часто просто лежит там, где его оставили.
    var text: String? { focused ?? hovered }

    private init() {}

    func set(_ text: String, isInside: Bool) {
        if isInside {
            hovered = text
        } else if hovered == text {
            // Только своё: курсор уже мог перейти на соседний значок,
            // и тот успел записаться раньше, чем этот сообщил об уходе.
            hovered = nil
        }
    }

    /// Подпись подсвеченного с клавиатуры. `nil` — подсветки нет.
    func focus(_ text: String?) {
        guard focused != text else { return }
        focused = text
    }

    /// Панель сменилась или закрылась — подпись уходит вместе с ней.
    ///
    /// Само наведение об этом не сообщит: кнопка исчезает вместе с панелью,
    /// и `onHover(false)` от неё уже не приходит. Без сброса плашка осталась
    /// бы висеть под свёрнутой чёлкой.
    func clear() {
        hovered = nil
        focused = nil
    }
}

/// Плашка с подписью под чёлкой.
///
/// Своя, а не системная всплывающая подсказка. Причин три: системная ждёт
/// секунду, прежде чем показаться; рисуется в чужом стиле; и всплывает
/// под курсором — то есть поверх самой чёлки, закрывая ровно тот значок,
/// про который рассказывает.
struct NotchHintBubble: View {
    let text: String?

    var body: some View {
        Text(text ?? "")
            .font(.system(size: NotchStyle.font(11), weight: .medium))
            .foregroundStyle(.white.opacity(NotchStyle.primaryOpacity))
            .lineLimit(1)
            .fixedSize()
            .padding(.horizontal, 10)
            .frame(height: NotchHintLayout.height)
            // Плашка лежит не на чёрном теле панели, а поверх чего попало:
            // обоев, чужого окна, светлого документа. Поэтому у неё своя
            // подложка, почти непрозрачная, и обводка с тенью — чтобы край
            // читался и на тёмном фоне тоже.
            .background(Capsule().fill(.black.opacity(0.92)))
            .overlay(Capsule().strokeBorder(.white.opacity(0.22), lineWidth: 0.5))
            .shadow(color: .black.opacity(0.45), radius: 10, y: 3)
            .opacity(text == nil ? 0 : 1)
            .animation(.easeOut(duration: 0.12), value: text)
    }
}

extension View {
    /// Подпись значка: имя для диктора и плашка под чёлкой для глаза.
    ///
    /// Один вызов вместо двух, потому что порознь их и забывали порознь:
    /// у шести кнопок оформления телесуфлера стоял `.help()` без имени,
    /// у пятнадцати остальных не было ни того ни другого.
    ///
    /// `.help()` здесь намеренно нет: две всплывающие подсказки разом —
    /// своя под чёлкой и системная под курсором — спорили бы друг с другом.
    /// - Parameter bubble: текст плашки, если он отличается от имени.
    ///   Расходятся они там, где кнопка переключает состояние: плашке идёт
    ///   живая фраза про то, что сейчас и что будет («Экран не гаснет —
    ///   нажмите, чтобы вернуть как было»), а имя обязано остаться прежним.
    ///   Диктор объявляет имя и **значение** порознь, и меняющееся имя он
    ///   прочтёт как другую кнопку, а не как ту же в другом состоянии.
    func notchHint(_ text: String, bubble: String? = nil) -> some View {
        let shown = bubble ?? text
        return self
            .onHover { inside in NotchHintTracker.shared.set(shown, isInside: inside) }
            .accessibilityLabel(text)
    }

    /// То же, но для элемента, у которого имя уже есть.
    ///
    /// Строка встречи, плитка нагрузки, кнопка подключения — у всех внутри
    /// свой текст, и SwiftUI выводит имя из него. Подменять его подписью
    /// действия было бы порчей: «Открыть в Календаре» вместо названия самой
    /// встречи диктор произнёс бы одинаково для всех строк подряд.
    ///
    /// Поэтому строка уходит в `accessibilityHint` — там она и место:
    /// подсказка отвечает на «что будет, если нажать», а не на «что это».
    func notchActionHint(_ text: String) -> some View {
        self
            .onHover { inside in NotchHintTracker.shared.set(text, isInside: inside) }
            .accessibilityHint(text)
    }
}

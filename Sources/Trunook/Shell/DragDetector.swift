import CoreGraphics
import Foundation

/// Отличает перетаскивание от нажатия.
///
/// Нужен зоне приёма файлов. Окно, принимающее перетаскивание, не может быть
/// прозрачным для мыши — система не разделяет эти два свойства, — поэтому
/// полоса под чёлкой ест нажатия по всему, что под ней. Лечится тем, что
/// окно оживает только на время перетаскивания, а определить этот момент
/// и есть здешняя работа.
///
/// Два входа, потому что ни одного не хватает по отдельности:
///
/// - **Опрос состояния кнопки.** Во время перетаскивания файлов мониторы
///   событий молчат, а положение кнопки читается всегда. Это основной путь.
/// - **Событие движения с зажатой кнопкой.** Приходит раньше ближайшего
///   опроса и выручает там, где кнопка не нажата вовсе — при перетаскивании
///   тремя пальцами система везёт файл без физической кнопки.
final class DragDetector {
    /// Насколько курсор должен отойти от точки нажатия, чтобы это считалось
    /// перетаскиванием. Простое нажатие оживлять зону приёма не должно —
    /// ради этого всё и затевалось.
    static let slop: CGFloat = 6

    /// Сколько перетаскивание считается идущим после последнего признака жизни.
    ///
    /// Запас, а не мгновенное «кнопку отпустили»: файл роняют именно
    /// отпусканием, и снять признак ровно в этот миг — значит рискнуть самим
    /// падением. Он же держит перетаскивание тремя пальцами, у которого
    /// нажатой кнопки нет вовсе.
    static let linger: TimeInterval = 0.6

    private(set) var isDragging = false

    /// Где курсор был, когда кнопку впервые увидели нажатой.
    private var pressOrigin: CGPoint?
    /// До какого момента перетаскивание считается идущим.
    private var until = Date.distantPast

    var onChange: ((Bool) -> Void)?

    /// Опрос: нажата ли кнопка и где курсор.
    func update(isPressed: Bool, at location: CGPoint, now: Date = Date()) {
        guard isPressed else {
            pressOrigin = nil
            if isDragging, now >= until { set(false) }
            return
        }

        guard let origin = pressOrigin else {
            // Первый тик с нажатой кнопкой — запоминаем, откуда считать путь.
            pressOrigin = location
            return
        }

        guard !isDragging else {
            note(now: now)
            return
        }
        guard hypot(location.x - origin.x, location.y - origin.y) >= Self.slop else { return }
        note(now: now)
    }

    /// Пришло событие движения с зажатой кнопкой — самый ранний признак.
    func note(now: Date = Date()) {
        until = now.addingTimeInterval(Self.linger)
        if !isDragging { set(true) }
    }

    private func set(_ dragging: Bool) {
        isDragging = dragging
        onChange?(dragging)
    }
}

/// Ловит ли окно выреза мышь.
///
/// Вынесено в отдельную функцию, а не оставлено условием по месту, потому что
/// ошибка здесь выключает кусок экрана. Окно, не прозрачное для мыши, съедает
/// нажатия **во всей своей рамке**, а не только там, где что-то нарисовано:
/// проверка попаданий в `NotchHostingView` решает лишь, какой вид внутри
/// получит событие, но наружу, в чужое приложение, его уже не пустит.
/// Рамка же размером с самую большую панель — под чёлкой это сотни точек
/// в обе стороны.
///
/// Класс ошибок известный, ловились четырежды:
///
/// 1. Полоса приёма файлов 185×128 под чёлкой съедала нажатия круглые сутки.
/// 2. Отсчёт до встречи держал окно непрозрачным всё то время, пока встреча
///    близка, — то есть по полчаса перед каждой.
/// 3. Пока курсор был в зоне выреза, окно ело нажатия во всей рамке, хотя
///    нарисована в ней бывает плашка 233×74. Полоса вокруг неё — сотни точек
///    вправо, влево и вниз — молча выключалась.
/// 4. Нажатия в этой же полосе пропадали, не закрывая накладку.
///
/// Правило поэтому одно и без исключений: **окно ловит мышь ровно там, где
/// что-то нарисовано, и нигде больше.** Не «пока открыта накладка», не «пока
/// наведено» — именно по нарисованному. Всё остальное чинится само:
/// нажатие мимо панели уходит в чужое приложение, а значит его видит
/// глобальный монитор и накладка закрывается, как и задумано.
enum NotchMouseCatch {
    /// - Parameters:
    ///   - hasSomethingDrawn: вырез показывает что-то сверх собственного
    ///     силуэта. Свёрнутый вырез нажатий не ждёт: под ним аппаратная чёлка,
    ///     и ловить там нечего.
    ///   - cursorOverVisibleRect: курсор внутри нарисованного прямо сейчас.
    ///   - isDraggingOut: с полки тащат файл наружу. Пока тащат, окно держим
    ///     непрозрачным во что бы то ни стало: перетаскивание начинается
    ///     внутри панели и уводит курсор за её край, и погасшее на полпути
    ///     окно оборвало бы его.
    static func catchesMouse(
        hasSomethingDrawn: Bool,
        cursorOverVisibleRect: Bool,
        isDraggingOut: Bool = false
    ) -> Bool {
        if isDraggingOut { return true }
        return hasSomethingDrawn && cursorOverVisibleRect
    }
}

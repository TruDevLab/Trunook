import SwiftUI

/// Оформление окна настроек.
///
/// Почти всё, что здесь когда-то было, теперь рисует система. Осталось два
/// решения: окно всегда тёмное и текст в нём растёт по настройке.
///
/// ## Почему цвета системные
///
/// Окно было выкрашено вручную: фон числом, полоса разделов числом, подложка
/// карточки, обводка карточки, обводка поля, заливка поля, выбранная строка,
/// три ступени текста — девять значений, и каждое приходилось выверять
/// по контрасту отдельно. Половину и правда пришлось поднимать: 0.38 давала
/// 3.57:1 при норме 4.5:1, обводка поля — 1.26:1 при норме 3:1.
///
/// Работа была не зря, но её вообще не нужно было делать. Системные цвета
/// приходят выверенными: `.secondaryLabelColor` держит норму на любом фоне
/// по определению, а при «увеличить контраст» и «уменьшить прозрачность»
/// система меняет их сама — сразу и правильно. Своим числам это приходилось
/// объяснять руками, и `dense()` в этом файле был именно таким объяснением.
///
/// Отсюда и вид окна: карточки, полосу разделов и поля рисуют `Form`, `List`
/// и обычные элементы управления, а не выписанные здесь прямоугольники.
/// Совпасть с системой самодельная карточка не может — она может только
/// отстать от неё на следующем обновлении.
///
/// ## Почему тёмное всегда
///
/// Приложение живёт в чёрном вырезе. Открыть настройки из чёрной панели
/// и получить белое окно — значит каждый раз спотыкаться о смену темы.
/// Оформление задаётся окну целиком, в `SettingsWindowController`
/// (`NSAppearance(named: .darkAqua)`), поэтому системные цвета сами приходят
/// тёмными, и подменять их здесь нечем и незачем.
enum SettingsStyle {
    // MARK: Текст
    //
    // Три ступени — те же, что были, но теперь они не числа, а роли.
    // Контраст держит система.

    /// Заголовок, значение, всё, что читают в первую очередь.
    static let title: Color = .primary
    /// Подпись рядом с элементом управления.
    static let secondary: Color = .secondary
    /// Пояснение под настройкой — самая тихая ступень.
    static let tertiary: Color = .secondary.opacity(0.75)

    // MARK: Акцент
    //
    // Один на окно: им красятся переключатели, ползунки и выбранная строка
    // в полосе разделов. Свой, а не системный синий, — это единственное
    // место, где приложение расписывается в собственном окне.

    static let accent = Palette.cyan

    // MARK: Размер текста

    /// Кегль в окне, увеличенный настройкой.
    ///
    /// Не через `NotchStyle`: вырез настройку не читает вовсе — под чёлкой
    /// ровно столько места, сколько оставила аппаратная вырезка. Окно
    /// ограничения не имеет и отдаёт все двести процентов, которых требует
    /// критерий доступности.
    ///
    /// Не округляется — по той же причине, что и в `WelcomeStyle`: округление
    /// схлопывает соседние ступени, а половину пункта отрисует сглаживание.
    static func font(_ size: CGFloat) -> CGFloat {
        size * textScale
    }

    /// Размер, подогнанный под кегль: сторона плитки, ширина поля, рама окна.
    ///
    /// Отдельно от `font`, но **тем же множителем**, и это тут главное.
    /// Порознь их развело сразу же: кегль значка в полосе разделов рос
    /// по настройке, а сторона плитки под ним стояла числом — на ста
    /// пятидесяти процентах значок вылезал за собственную подложку.
    ///
    /// Ровно то, от чего предостерегает `NotchStyle`: «все кегли и все
    /// размеры, которые под них подогнаны, проходят через один множитель».
    /// Предостережение было написано, прочитано и всё равно нарушено —
    /// поэтому теперь оно ещё и здесь, рядом с местом нарушения.
    ///
    /// Округляется, в отличие от кегля: это точки на экране, и половина
    /// точки в раме оборачивается размытым краем.
    static func scaled(_ size: CGFloat) -> CGFloat {
        (size * textScale).rounded()
    }

    private static var textScale: CGFloat {
        CGFloat(Settings.shared.textScale) / 100
    }

    // MARK: Размеры, подогнанные под кегль

    /// Сторона цветной плитки со значком в полосе разделов.
    static var glyphSide: CGFloat { scaled(20) }
    /// Её скругление. Повторяет системное: у Apple в «Системных настройках»
    /// значок раздела лежит в скруглённом квадрате той же плотности.
    static var glyphRadius: CGFloat { scaled(6) }

    /// Поле записи сочетания клавиш.
    static var hotKeyField: CGSize {
        CGSize(width: scaled(140), height: scaled(24))
    }
    /// Оно же в списке команд — там строка теснее.
    static var hotKeyFieldNarrow: CGSize {
        CGSize(width: scaled(130), height: scaled(24))
    }

    /// Наибольшая ширина списка выбора: шире он смотрится пустым.
    static var pickerWidth: CGFloat { scaled(300) }
    /// Поле ввода названия города.
    static var searchFieldWidth: CGFloat { scaled(260) }
    /// Строка с найденным городом.
    static var resultWidth: CGFloat { scaled(220) }

    // MARK: Размер окна

    /// Основание, от которого считается окно. Подобрано под сто процентов.
    static let baseWindow = CGSize(width: 210 + 460, height: 640)
    static var sidebarWidth: CGFloat { scaled(210) }

    /// Окно растёт вместе с текстом — иначе выросшие строки обрезались бы
    /// прежней рамой. Потолок задаёт экран: `SettingsWindowController`
    /// ужимает по видимой области.
    static var windowSize: CGSize {
        CGSize(width: scaled(baseWindow.width), height: scaled(baseWindow.height))
    }
}

import CoreGraphics

/// Кегли окна знакомства и размеры, подогнанные под них.
///
/// До этого файла окно было единственным местом в приложении, где кегль стоял
/// числом по месту: сорок три вызова `.font(.system(size:))` на тринадцать
/// разных значений — 10, 11, 11.5, 12, 12.5, 13, 13.5, 14.5, 15, 26, 30, 36
/// и 42. Панели выреза давно ходили через `NotchStyle`, окно настроек — через
/// `SettingsStyle`, и только знакомство жило по-старому.
///
/// Обиднее всего это выходило потому, что знакомство человек видит первым.
/// Тот, кто увеличил текст в системе, ставил галочки в разрешениях вслепую:
/// настройка размера до окна не доходила вовсе.
///
/// Названия по роли, а не по числу: числа сходятся и расходятся, роль
/// у строки одна. Заодно сошлись близнецы — 13 и 13.5 были одним и тем же
/// заголовком карточки, набранным дважды.
enum WelcomeStyle {
    // MARK: Масштаб
    //
    // Не через `NotchStyle.scaled`: там множитель ограничен полутора, потому
    // что панель прибита к верхней кромке экрана и шире неё быть не может.
    // Окно ограничения не имеет — оно растёт, и с этого файла ещё и тянется
    // мышью, — поэтому берёт все двести процентов, которых требует критерий.
    //
    // Кегли и размеры под них проходят через один множитель, как в `NotchStyle`.
    // Порознь их не масштабировать: значок, выросший в плитке прежней стороны,
    // упрётся в её край, а строка в карточке прежней ширины перенесётся
    // посередине слова.

    static var textScale: CGFloat {
        CGFloat(Settings.shared.textScale) / 100
    }

    /// Размер, подогнанный под кегль: сторона плитки, ширина карточки, рама
    /// окна. Округляется — это точки на экране, и половина точки в раме
    /// оборачивается размытым краем.
    static func scaled(_ value: CGFloat) -> CGFloat {
        (value * textScale).rounded()
    }

    /// Кегль. В отличие от размеров, **не** округляется.
    ///
    /// Округление было и стоило двух ступеней сразу: 12.5 и 13 обе давали 13,
    /// 11.5 и 12 — обе 12. Лестница из девяти ступеней превращалась в семь
    /// ровно на ста процентах, то есть в самом обычном случае, и различить
    /// название карточки и текст под ним стало нечем.
    ///
    /// Половина пункта в кегле законна — исходная вёрстка ей и пользовалась,
    /// — а на экране её отрисует сглаживание. Проверку на схлопывание держит
    /// `WelcomeStyleTests.лестницаУбывает`.
    static func font(_ value: CGFloat) -> CGFloat {
        value * textScale
    }

    // MARK: Лестница кеглей

    /// Название приложения на первом экране.
    static var hero: CGFloat { font(42) }
    /// «Всё готово» на последнем.
    static var finale: CGFloat { font(30) }
    /// Заголовок шага.
    static var chapter: CGFloat { font(26) }
    /// Строка под названием приложения.
    static var deck: CGFloat { font(14.5) }
    /// Название карточки, надпись на кнопке.
    static var title: CGFloat { font(13) }
    /// Основной текст карточки.
    static var body: CGFloat { font(12.5) }
    /// Пояснение под ним.
    static var detail: CGFloat { font(12) }
    /// Подпись под значком, второстепенная строка.
    static var caption: CGFloat { font(11.5) }
    /// Надпись над заголовком, сочетание клавиш.
    static var micro: CGFloat { font(10) }

    // MARK: Размеры, подогнанные под кегль

    /// Значок внутри карточки — рядом со строкой, набранной `caption`.
    static var glyph: CGFloat { font(15) }
    /// Сторона цветной плитки со значком (`WelcomeGlyph`).
    static var tile: CGFloat { scaled(32) }
    /// Галочка последнего шага и круг под ней.
    static var mark: CGFloat { font(36) }
    static var markWell: CGFloat { scaled(92) }

    /// Плитка возможности: значок и слово под ним.
    static var featureTile: CGSize {
        CGSize(width: scaled(88), height: scaled(62))
    }

    /// Карточка подсказки: ширина держит строку, высота растёт по тексту.
    static var hintCardWidth: CGFloat { scaled(216) }

    /// Строка сочетания клавиш справа от названия команды.
    static var shortcutField: CGSize {
        CGSize(width: scaled(132), height: scaled(26))
    }

    // MARK: Размер окна

    /// Основание, от которого считается окно. Подобрано под сто процентов.
    static let baseWindow = CGSize(width: 780, height: 700)

    /// Окно растёт вместе с текстом.
    ///
    /// Иначе масштабирование было бы бессмысленным: строки выросли бы
    /// в прежней раме и обрезались об неё. Потолок задаёт экран — обрезать
    /// окно его кромкой всё равно придётся, но тогда содержимое достаётся
    /// прокруткой, а не пропадает.
    static var windowSize: CGSize {
        CGSize(width: scaled(baseWindow.width), height: scaled(baseWindow.height))
    }
}
